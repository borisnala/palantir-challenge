// Packs the static build (out/) into router/site.js so the router Worker serves Risk Desk by itself.
// A Pages upload does not work from the cloud session (its network swaps the upload's own pass for the API token),
// a Worker upload does. Text files go in as strings, everything else as base64.
//   node scripts/pack-worker.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const OUT = "out";
const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".json": "application/json", ".txt": "text/plain; charset=utf-8", ".svg": "image/svg+xml", ".ico": "image/x-icon",
  ".png": "image/png", ".woff2": "font/woff2", ".webmanifest": "application/manifest+json" };
const TEXT = new Set([".html", ".js", ".css", ".json", ".txt", ".svg", ".webmanifest"]);
const files = {};
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const rel = "/" + relative(OUT, p).replace(/\\/g, "/");
    const ext = extname(p);
    const buf = readFileSync(p);
    files[rel] = [TYPES[ext] ?? "application/octet-stream", TEXT.has(ext) ? 0 : 1, TEXT.has(ext) ? buf.toString("utf8") : buf.toString("base64")];
  }
})(OUT);
writeFileSync("router/site.js", "// Generated by scripts/pack-worker.mjs from out/. Do not edit.\nexport default " + JSON.stringify(files) + ";\n");
console.log(`packed ${Object.keys(files).length} files`);
